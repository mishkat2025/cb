"""Proposal completion (2026-10-22): Module III before and after M19 (CVDC representation inside Module III) and M20
(angular-velocity channel), E01-E04.

Variants (cvdc.assess.run output folders): the published Module III (outputs/full/phase4, M17 / M18), velocity only,
CVDC alignment only, and both (= the completed Module III, configs/completion.yaml). Per stratum (exercise x group, and
pooled within group with every score centred on its exercise mean): Spearman of the set score with the
physiotherapists' total score and MQ [95% CI], the paired difference to the published Module III on the same subject
draws; the out-of-fold predictor RMSE vs the group mean and the view stability of the rep score (from each variant's
report_module3.py output); the firing rates of the two new rules.

usage: python scripts/full/completion/module3_comparison.py [--loso]
  --loso: the LOSO runs (module3_loso_original vs module3_loso) instead of GroupKFold-5.
Writes <results>/completion/module3_comparison[_loso]/{agreement.csv, summary.md}.
"""
import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "scripts" / "pilot" / "phase4"))
from cvdc.config import load_config, resolve  # noqa: E402
from report_phase4 import paired_rho  # noqa: E402

EXS = ["E01", "E02", "E03", "E04"]


def variants(res, loso):
    c = res / "completion"
    if loso:
        return {"published Module III (LOSO libraries)": c / "module3_loso_original",
                "completed (M19 + M20, LOSO)": c / "module3_loso"}
    return {"published Module III": resolve("outputs/full/phase4"), "+ angular velocity (M20)": c / "module3_velocity_only",
            "+ CVDC alignment (M19)": c / "module3_join_only", "completed (M19 + M20)": c / "module3"}


def f(x, d=2):
    return "–" if x is None or not np.isfinite(x) else f"{x:.{d}f}".replace("-", "−")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/completion.yaml")
    ap.add_argument("--loso", action="store_true")
    ap.add_argument("--boot", type=int)
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    t0 = time.time()
    cfg = load_config(REPO / a.config)
    ec = cfg["eval"]
    n_boot, ci, seed = a.boot or ec["bootstrap"]["n"], ec["bootstrap"]["ci"], ec["bootstrap"]["seed"]
    res = resolve(ec["results_dir"])
    out = res / "completion" / ("module3_comparison_loso" if a.loso else "module3_comparison")
    out.mkdir(parents=True, exist_ok=True)
    VAR = variants(res, a.loso)
    names = list(VAR)
    V = None
    for i, (nm, d) in enumerate(VAR.items()):
        v = pd.read_csv(d / "module3_videos.csv")
        v = v[v.exercise.isin(EXS)]
        col = f"s{i}"
        if V is None:
            V = v[["video_id", "exercise", "subject", "group", "score", "MQ", "ref_set_score"]].rename(
                columns={"ref_set_score": col})
        else:
            V = V.merge(v[["video_id", "ref_set_score"]].rename(columns={"ref_set_score": col}), on="video_id",
                        validate="one_to_one")
    cols = [f"s{i}" for i in range(len(names))]
    rows = []
    strata = [(f"{e} {g}", e, g) for e, g in sorted({(e, g) for e, g in zip(V.exercise, V.group)})] + \
             [("experts, E01–E04", None, "expert"), ("non-experts, E01–E04", None, "non-expert")]
    for sname, ex, grp in strata:
        d = V[((V.exercise == ex) if ex else True) & (V.group == grp)].sort_values("video_id").copy()
        if ex is None:  # pooled: centre every score on its exercise mean
            for c in cols + ["score", "MQ"]:
                d[c] = d[c] - d.groupby("exercise")[c].transform("mean")
        for r in paired_rho(d, cols, ["score", "MQ"], n_boot, seed, ci, {}, ex, grp):
            rows.append(dict(stratum=sname, variant=names[cols.index(r.pop("column"))], **r))
    A = pd.DataFrame(rows)
    A.to_csv(out / "agreement.csv", index=False)

    L = [f"# Module III before and after the proposal-completion changes (E01–E04, "
         f"{'LOSO' if a.loso else 'GroupKFold-5'} libraries)\n",
         "Generated by `scripts/full/completion/module3_comparison.py`. M19 = the CVDC representation inside Module III "
         "(alignment in the Proposed model's embedding space, an embedding-distance score group and rule); M20 = the "
         "angular-velocity channel. Spearman ρ of the set score with the physiotherapists' score [95% CI, subject "
         f"bootstrap, {n_boot} draws]; Δ vs the published Module III on the same draws (bold: CI excludes 0). Pooled "
         "rows: centred within exercise.\n"]
    for t, tn in (("score", "total score"), ("MQ", "movement-quality score")):
        L.append(f"\n## Agreement with the {tn}\n")
        L.append("| Stratum | " + " | ".join(names) + " |")
        L.append("|" + "---|" * (len(names) + 1))
        for sname, _, _ in strata:
            g = A[(A.stratum == sname) & (A.target == t)].set_index("variant")
            cells = []
            for nm in names:
                r = g.loc[nm]
                s = f"{f(r.rho)} [{f(r.lo)}, {f(r.hi)}]"
                if np.isfinite(r.get("delta", np.nan)):
                    dd = f"Δ {f(r.delta)} [{f(r.delta_lo)}, {f(r.delta_hi)}]"
                    s += f" ({'**' + dd + '**' if (r.delta_lo > 0 or r.delta_hi < 0) else dd})"
                cells.append(s)
            L.append(f"| {sname} | " + " | ".join(cells) + " |")
    # predictor and view stability from each variant's report_module3.py output
    L.append("\n## Out-of-fold predictor vs the group mean (total score) and view stability\n")
    L.append("Predictor: a within-group line total ~ set score fitted per fold on the training videos, RMSE minus the "
             "group-mean baseline's (negative = better). View stability: ICC(1) of the rep score over synced expert "
             "performances (the same rep from F / L / R).\n")
    L.append("| Exercise | " + " | ".join(f"{nm}: ΔRMSE experts / non-experts; ICC" for nm in names) + " |")
    L.append("|" + "---|" * (len(names) + 1))
    for ex in EXS:
        cells = []
        for nm, d in VAR.items():
            p = d / "predictor.csv"
            s = d / "view_stability.csv"
            if not p.exists() or not s.exists():
                cells.append("–")
                continue
            P = pd.read_csv(p)
            P = P[(P.exercise == ex) & (P.target == "score")].set_index("group")
            S = pd.read_csv(s)
            S = S[(S.exercise == ex) & (S.measure == "Module III score")]
            pe = f(P.loc["expert", "delta"]) if "expert" in P.index else "–"
            pn = f(P.loc["non-expert", "delta"]) if "non-expert" in P.index else "–"
            icc = f(S.icc.iloc[0]) if len(S) and "icc" in S.columns else "–"
            cells.append(f"{pe} / {pn}; {icc}")
        L.append(f"| {ex} | " + " | ".join(cells) + " |")
    last = VAR[names[-1]] / "rule_rates.csv"
    if last.exists():
        RR = pd.read_csv(last)
        RR = RR[RR.rule.isin(["angular_velocity_deviation", "movement_pattern_deviation"]) & RR.exercise.isin(EXS)]
        L.append("\n## The new rules (completed Module III): share of reps flagged\n")
        L.append("| Exercise | rule | experts' videos ≥ 95 | experts' videos < 80 | non-experts |")
        L.append("|---|---|---|---|---|")
        for r in RR.itertuples():
            L.append(f"| {r.exercise} | {r.rule} | {f(100 * r.experts_ge95, 0)}% | {f(100 * r.experts_lt80, 0)}% | "
                     f"{f(100 * r.non_experts, 0) + '%' if np.isfinite(r.non_experts) else '–'} |")
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"written to {out} ({time.time() - t0:.0f} s)")


if __name__ == "__main__":
    main()
