"""The pipeline's output (X11, 2026-10-22): generated tables for the final report's main results.

The proposal's pipeline (Fig. 3) outputs Module III's score: with the CVDC representation inside Module III (M19)
and the angular-velocity channel (M20), as run by ``python -m cvdc.assess.run --config configs/completion.yaml``
(GroupKFold-5 libraries) and with ``--loso --join perex_loso`` (LOSO libraries). This script turns those runs'
summaries (scripts/full/phase4/report_module3.py and scripts/full/completion/module3_comparison.py, run first) into
reports/pipeline_tables.md; the rule-based Module III without the network (M17 / M18) is the comparison row.

  1  agreement of the set score with the physiotherapists (total score and MQ), within groups and pooled, LOSO and
     GroupKFold-5, with the paired difference to the rule-based Module III
  2  the set score as a predictor: out-of-fold within-group line vs the group mean (RMSE)
  3  view stability of the rep score over synced expert performances (ICC)
  4  expert vs non-expert separation (AUC) of the set score
  5  firing rates of every rule (share of reps): experts' videos >= 95, < 80, non-experts

usage: python scripts/full/final/report_pipeline.py
"""
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO))
from cvdc.config import load_config, resolve  # noqa: E402

EXS = ["E01", "E02", "E03", "E04"]


def f(x, d=2):
    return "–" if x is None or not np.isfinite(x) else f"{x:.{d}f}".replace("-", "−")


def ci(r, k="rho", lo="lo", hi="hi", d=2, bold=False):
    s = f"{f(r[k], d)} [{f(r[lo], d)}, {f(r[hi], d)}]"
    return f"**{s}**" if bold and (r[lo] > 0 or r[hi] < 0) else s


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(r) + " |" for r in rows]


def main():
    cfg = load_config(REPO / "configs" / "completion.yaml")
    c = resolve(cfg["eval"]["results_dir"]) / "completion"
    runs = {"LOSO": c / "module3_loso", "GroupKFold-5": c / "module3"}
    comp = {"LOSO": c / "module3_comparison_loso" / "agreement.csv",
            "GroupKFold-5": c / "module3_comparison" / "agreement.csv"}
    L = ["# The pipeline's output: Module III with the CVDC representation (E01–E04)\n",
         f"Generated by `scripts/full/final/report_pipeline.py` on {time.strftime('%Y-%m-%d %H:%M')} from the Module III "
         "runs in `outputs/full/results/completion/` (decisions M19, M20, X11). **Pipeline** = Module III with the "
         "Proposed model's CVDC representation (alignment in the embedding space, embedding-distance and "
         "angular-velocity parts); **rule-based** = Module III without any network (M17 / M18), the comparison. 95% "
         "CIs from the subject bootstrap (2,000 draws); LOSO is the final scheme, GroupKFold-5 the reference.\n"]

    L.append("\n## 1. Agreement of the set score with the physiotherapists\n")
    L.append("Spearman ρ [95% CI]; Δ = pipeline − rule-based on the same draws (bold: CI excludes 0). Pooled rows: "
             "centred within exercise.\n")
    for scheme, p in comp.items():
        A = pd.read_csv(p)
        variants = list(dict.fromkeys(A.variant))
        base, pipe = variants[0], variants[-1]
        rows = []
        for st in dict.fromkeys(A.stratum):
            cells = [st]
            for t in ("score", "MQ"):
                a = A[(A.stratum == st) & (A.target == t)].set_index("variant")
                r = a.loc[pipe]
                cells += [ci(r), ci(a.loc[base]),
                          ci(r, "delta", "delta_lo", "delta_hi", bold=True)]
            rows.append(cells)
        L.append(f"\n**{scheme}**\n")
        L += table(["Stratum", "total: pipeline", "total: rule-based", "total: Δ", "MQ: pipeline", "MQ: rule-based",
                    "MQ: Δ"], rows)

    L.append("\n## 2. The set score as a predictor of the physiotherapists' total score\n")
    L.append("A within-group line total ~ set score, fitted per fold on the training videos and applied to the test "
             "videos: its RMSE, the group mean's RMSE, and the difference [95% CI] (negative = the set score adds "
             "information; bold: CI excludes 0).\n")
    rows = []
    for scheme, d in runs.items():
        P = pd.read_csv(d / "predictor.csv")
        P = P[(P.target == "score") & P.exercise.isin(EXS)]
        for r in P.itertuples():
            bold = r.delta_lo > 0 or r.delta_hi < 0
            dd = f"{f(r.delta)} [{f(r.delta_lo)}, {f(r.delta_hi)}]"
            rows.append([scheme, f"{r.exercise} {r.group}", f(r.rmse_line), f(r.rmse_group_mean),
                         f"**{dd}**" if bold else dd])
    L += table(["Scheme", "Stratum", "line RMSE", "group-mean RMSE", "Δ RMSE"], rows)

    L.append("\n## 3. View stability of the rep score (synced expert performances)\n")
    L.append("ICC(1) [95% CI] of the same rep scored from the front, left and right camera; the score without its "
             "speed part as a check (synced views share rep timing).\n")
    rows = []
    for scheme, d in runs.items():
        V = pd.read_csv(d / "view_stability.csv")
        V = V[V.exercise.isin(EXS)]
        for ex in EXS:
            v = V[V.exercise == ex].set_index("measure")
            rows.append([scheme, ex, ci(v.loc["Module III score"], "icc", "icc_lo", "icc_hi"),
                         ci(v.loc["score without speed"], "icc", "icc_lo", "icc_hi")])
    L += table(["Scheme", "Exercise", "rep score", "rep score without speed"], rows)

    L.append("\n## 4. Expert vs non-expert separation of the set score\n")
    L.append("AUC [95% CI] (exercises with both groups); a high AUC partly reflects the group differences in clip "
             "length and recording set-up (E9–E12), not only movement quality.\n")
    S = pd.read_csv(runs["LOSO"] / "separation.csv")
    S = S[S.exercise.isin(EXS)]
    L += table(["Exercise", "subset", "AUC", "mean set score experts / non-experts"],
               [[r.exercise, r.subset, ci(r._asdict(), "auc", "auc_lo", "auc_hi"),
                 f"{f(r.score_expert, 1)} / {f(r.score_non_expert, 1)}"] for r in S.itertuples()])

    L.append("\n## 5. Rule firing rates (pipeline, LOSO libraries)\n")
    L.append("Share of reps on which each rule fires: in the experts' videos the physiotherapists scored ≥ 95 and "
             "< 80, and in the non-experts' videos. No error-type labels exist, so these rates are what can be "
             "reported; a useful rule fires more often in the weaker videos.\n")
    RR = pd.read_csv(runs["LOSO"] / "rule_rates.csv")
    RR = RR[RR.exercise.isin(EXS)]
    pct = lambda x: "–" if not np.isfinite(x) else f"{100 * x:.0f}%"  # noqa: E731
    L += table(["Exercise", "rule", "experts ≥ 95", "experts < 80", "non-experts"],
               [[r.exercise, f"`{r.rule}`", pct(r.experts_ge95), pct(r.experts_lt80), pct(r.non_experts)]
                for r in RR.itertuples()])
    out = REPO / "reports" / "pipeline_tables.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"written {out}")


if __name__ == "__main__":
    main()
